def write_xlsx():
    from openpyxl import Workbook
    from openpyxl.styles import Font, Alignment, PatternFill, Border, Side
    from openpyxl.utils import get_column_letter

    wb = Workbook()

    ink = "231F19"; zhu = "B03A2E"; paper = "FBF8F1"; alt = "FCFAF5"
    thin = Side(style="thin", color="D2C8B2")
    border = Border(left=thin, right=thin, top=thin, bottom=thin)

    def build(ws, headers, rows, widths):
        ws.append(headers)
        for c in range(1, len(headers)+1):
            cell = ws.cell(row=1, column=c)
            cell.font = Font(bold=True, color="F7F3EA", size=10.5, name="Microsoft YaHei")
            cell.fill = PatternFill("solid", fgColor=ink)
            cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
            cell.border = border
        ws.row_dimensions[1].height = 26
        for i, r in enumerate(rows, start=2):
            ws.append(list(r))
            for c in range(1, len(headers)+1):
                cell = ws.cell(row=i, column=c)
                cell.font = Font(size=10, name="Microsoft YaHei")
                cell.alignment = Alignment(vertical="top", wrap_text=True)
                cell.border = border
                if i % 2 == 0:
                    cell.fill = PatternFill("solid", fgColor=alt)
            ws.cell(row=i, column=1).font = Font(size=10, bold=True, color=zhu, name="Microsoft YaHei")
            ws.cell(row=i, column=1).alignment = Alignment(horizontal="center", vertical="top")
        for idx, w in enumerate(widths, start=1):
            ws.column_dimensions[get_column_letter(idx)].width = w
        ws.freeze_panes = "A2"

    ws1 = wb.active
    ws1.title = "序幕分镜48镜"
    build(ws1,
          ["镜号","时间","景别","机位","运镜","时长(秒)","画面内容","声音 / 台词"],
          prologue, [6,8,7,9,11,9,58,46])

    ws2 = wb.create_sheet("第八集高潮段36镜")
